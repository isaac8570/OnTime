// 🚀 OnTime 앱 전체 워크플로우

// 1️⃣ 캘린더 일정 자동 읽기
캘린더에서 "오후 3시 홍대 카페에서 친구 만나기" 일정 감지
↓
AI가 텍스트 분석: "홍대 카페" → "홍대입구역" 추출
↓

// 2️⃣ 실시간 경로 계산  
현재 위치(GPS) → 홍대입구역
Google Maps API: "대중교통 25분, 자가용 15분, 도보 45분"
↓

// 3️⃣ 스마트 출발 시간 계산
일정 시간: 오후 3시
이동 시간: 25분 (대중교통)
여유 시간: 5분
→ 출발 시간: 오후 2시 30분
↓

// 4️⃣ 개인화된 알림 발송
RAG 시스템이 과거 패턴 분석:
"홍대는 보통 5분 더 걸려요. 지금 출발하면 딱 맞을 것 같아요! 🚇"
↓

// 5️⃣ 실제 사용 데이터 자동 학습
사용자가 실제로 2시 35분에 출발 → 3시 5분 도착 (5분 늦음)
→ Firebase에 자동 저장: "홍대 + 월요일 + 맑음 = 5분 지연"
↓

// 6️⃣ 다음번 더 정확한 예측
다음 홍대 일정 시:
"지난번 5분 늦었어요. 이번엔 2시 25분에 출발하세요! 💪"

